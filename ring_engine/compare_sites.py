"""Run every trencher variant on every site/soil scenario and tabulate the results.

    python3 compare_sites.py                      # full matrix, all cores
    python3 compare_sites.py --res 320 --only home_2wd,t6_25_b400 --soils florida_sand

Writes output/compare/<scenario>__<vehicle>/ (report, images, section) and
output/compare/COMPARISON.md + comparison.json.
"""
import argparse
import json
import multiprocessing as mp
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

SCENARIOS = {
    "florida_sand": {"label": "Florida sand lot (flat)", "overrides": ['soil.preset="florida_sand"',
                                                                        'site={"type": "flat"}']},
    "ne_till": {"label": "New England till, 6 ft slope", "overrides": ['soil.preset="ne_glacial_till"']},
    "ne_till_wet": {"label": "New England till, 6 ft slope, wet spring",
                    "overrides": ['soil.preset="ne_glacial_till_wet"']},
}


def run_one(job):
    import tether_sim as ts
    from config import load_config
    from eox_vehicle import load_fleet
    scen, vkey, res, max_h, out_root = job
    ov = list(SCENARIOS[scen]["overrides"]) + ["operations.max_sim_hours=%d" % max_h]
    if res:
        ov.append("grid.resolution=%d" % res)
    cfg = load_config(ts.DEFAULT_PARAMS, ov)
    veh = load_fleet()[vkey]
    out = os.path.join(out_root, "%s__%s" % (scen, vkey))
    lines = []
    t0 = time.time()
    sim = ts.TetherSim(cfg, veh, log=lines.append)
    rep = sim.run()
    rep["scenario"]["key"] = scen
    rep["scenario"]["vehicle_key"] = vkey
    rep["vehicle_spec"] = {k: veh[k] for k in ("mass_kg", "ballast_kg", "drive") if k in veh}
    rep["vehicle_spec"]["tool"] = veh["tool"]["type"]
    rep["vehicle_spec"]["bus"] = veh.get("bus")
    done = rep["achieved"]["moat_completion_pct"] / 100.0
    rep["time"]["projected_total_h"] = (rep["time"]["total_h"] / done if done > 0.01 else None)
    ts.print_report(rep, log=lines.append)
    ts.write_outputs(sim, rep, out)
    with open(os.path.join(out, "log.txt"), "w") as fh:
        fh.write("\n".join(lines))
    print("[%5.0fs] %-14s %-12s %5.1f%% complete, %8.0f h" % (time.time() - t0, scen, vkey,
                                                            100 * done, rep["time"]["total_h"]), flush=True)
    return rep


def fmt(n, d=0):
    if n is None:
        return "-"
    return ("{:,.%df}" % d).format(n)


ELECTRICITY_USD_PER_KWH = 0.25     # ASSUMED New England / Florida residential blend
LABOUR_USD_PER_H = 40.0            # ASSUMED: someone attends refusals and stalls


def baseline_rows(scen, res):
    import tether_sim as ts
    from config import load_config
    from conventional import estimate, fleet_makespan, load_machines, moat_geometry
    from terrain_engine import Terrain
    ov = list(SCENARIOS[scen]["overrides"]) + ["grid.resolution=%d" % res]
    cfg = load_config(ts.DEFAULT_PARAMS, ov)
    T = Terrain(cfg)
    data = load_machines()
    geo = moat_geometry(T, cfg)
    rows = []
    for key, mach in data["machines"].items():
        e = estimate(cfg, T, mach, data["job"], geo)
        mh = [p["hours"] for p in e["per_moat"]]
        e["fleet2_days"] = fleet_makespan(mh, 2) / e["hours_per_day"]
        e["key"] = key
        rows.append(e)
    return rows


def eox_cost(r):
    e, m, t = r["energy"], r["machine"], r["time"]
    return (e["grid_kwh"] * ELECTRICITY_USD_PER_KWH
            + (t["rock_delay_h"] + t["stall_h"]) * LABOUR_USD_PER_H)


def table(reports, out_root, res):
    from conventional import fleet_makespan
    by = {}
    for r in reports:
        by.setdefault(r["scenario"]["key"], []).append(r)
    md = ["# Building the Atlantean site: tractor loader-backhoes vs eOx trenchers", "",
          "Generated by `compare_sites.py`. Garden-scale site (2 moats, 2 berms, about 100 m across), moats cut "
          "to a level waterline with 0.3 m freeboard. Screening estimates: machine data in `vehicles/`, soils "
          "in `soils.json`, assumptions in `conventional.py` and `tether_sim.py`.", "",
          "- **TLB** hours are operator hours (%s h days); cost = rental with operator + fuel + delivery + pump. "
          "**eOx** hours are unattended machine hours on the tether (10 h days); cost = electricity at $%.2f/kWh "
          "+ $%.0f/h labour for refusals and stalls, excluding the machine itself."
          % (8, ELECTRICITY_USD_PER_KWH, LABOUR_USD_PER_H),
          "- **Fleet** columns: several identical machines working at once, one per moat first, then sharing a "
          "moat at 85%% efficiency each.", ""]
    for scen, reps in by.items():
        d = reps[0]["design"]
        md += ["## %s" % SCENARIOS[scen]["label"], "",
               "Design: **%s m3** bank cut (deepest %.2f m), %s m3 loose fill; existing relief %.2f m (%.1f ft). "
               "Soil: %s." % (fmt(d["V_cut_bank_m3"]), d["max_cut_m"], fmt(d["V_fill_loose_m3"]),
                              d["existing_relief_m"], d["existing_relief_m"] / 0.3048,
                              reps[0]["scenario"]["soil_label"]), "",
               "### Conventional baseline", "",
               "| Machine | Hours | Days (8 h) | Days, 2 machines | m3/h | Cost | $/m3 | Reaches full depth |",
               "|---|---|---|---|---|---|---|---|"]
        for e in baseline_rows(scen, res):
            md.append("| %s | %s | %.0f | %.0f | %.1f | $%s | %.0f | %s |"
                      % (e["machine"], fmt(e["hours"]), e["working_days"], e["fleet2_days"], e["m3_per_hour"],
                         fmt(e["cost_usd"]), e["usd_per_bank_m3"],
                         "yes" if e["reaches_full_depth"] else "no: %s m3 dug from a bench" % fmt(e["bench_m3"])))
        md += ["", "### eOx on the tether", "",
               "| Vehicle | Mass kg | Rated / peak pull N | Done % | Machine hours | Days (10 h) | 2 machines | "
               "4 machines | m3/h | Motor cooling h | Refusals | kWh/m3 | Run cost | Cut limited by grip / heat |",
               "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        reps.sort(key=lambda r: r["time"]["projected_total_h"] or 1e12)
        for r in reps:
            vs, t, a, m, e = r["vehicle_spec"], r["time"], r["achieved"], r["machine"], r["energy"]
            u = vs["drive"].get("units", 1)
            hours = t["projected_total_h"] if a["aborted"] else t["total_h"]
            star = "*" if a["aborted"] else ""
            hpd = t["hours_per_day"]
            bm = t.get("by_moat_h") or [hours]
            f2 = fleet_makespan(bm, 2) / hpd
            f4 = fleet_makespan(bm, 4) / hpd
            md.append("| %s | %s | %s / %s | %.1f | %s%s | %s%s | %.0f | %.0f | %.2f | %s | %s | %.2f | $%s | %.0f%% / %.0f%% |"
                      % (r["scenario"]["vehicle"], fmt(vs["mass_kg"] + vs.get("ballast_kg", 0)),
                         fmt(vs["drive"]["rated_force_n"] * u), fmt(vs["drive"]["peak_force_n"] * u),
                         a["moat_completion_pct"], fmt(hours), star, fmt(hours / hpd), star, f2, f4,
                         t["m3_per_hour"], fmt(t["motor_cooling_h"]), fmt(m["rock_refusals"]),
                         e["kwh_per_bank_m3"], fmt(eox_cost(r)), m["limit_grip_pct"], m.get("limit_heat_pct", 0)))
        md.append("")
    md += ["`*` run stopped at the simulated-hours cap; hours are projected from the fraction completed.", ""]
    with open(os.path.join(out_root, "COMPARISON.md"), "w") as fh:
        fh.write("\n".join(md))
    with open(os.path.join(out_root, "comparison.json"), "w") as fh:
        json.dump(reports, fh, indent=1, default=float)
    return "\n".join(md)


def main():
    from eox_vehicle import load_fleet
    p = argparse.ArgumentParser()
    p.add_argument("--res", type=int, default=448)
    p.add_argument("--max-hours", type=int, default=25000)
    p.add_argument("--only", help="comma-separated vehicle keys")
    p.add_argument("--soils", help="comma-separated scenario keys")
    p.add_argument("--jobs", type=int, default=max(1, mp.cpu_count() - 1))
    p.add_argument("--out", default=os.path.join(HERE, "output", "compare"))
    a = p.parse_args()
    vkeys = a.only.split(",") if a.only else list(load_fleet().keys())
    skeys = a.soils.split(",") if a.soils else list(SCENARIOS)
    os.makedirs(a.out, exist_ok=True)
    jobs = [(s, v, a.res, a.max_hours, a.out) for s in skeys for v in vkeys]
    jobs.sort(key=lambda j: (j[1] != "home_2wd", j[0] == "florida_sand"))   # slow ones first
    print("%d runs on %d workers" % (len(jobs), a.jobs), flush=True)
    with mp.Pool(a.jobs) as pool:
        reports = pool.map(run_one, jobs, chunksize=1)
    print(table(reports, a.out, a.res))


if __name__ == "__main__":
    main()
